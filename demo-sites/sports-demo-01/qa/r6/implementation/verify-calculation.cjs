const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const Module = require('node:module');
const site = path.resolve(__dirname, '../../..', 'site');
const ts = require(path.join(site, 'node_modules/typescript'));
const filename = path.join(site, 'app/demo-data.ts');
const source = fs.readFileSync(filename, 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS,esModuleInterop:true,target:ts.ScriptTarget.ES2020}}).outputText;
const mod = new Module(filename, module);
mod.filename = filename;
mod.paths = Module._nodeModulePaths(path.dirname(filename));
mod._compile(compiled, filename);
const {matches, totalsFor, validateStake, priceText} = mod.exports;
const pick = (i, p=0) => ({id:`${matches[i].id}-0-${p}`,matchId:matches[i].id,marketIndex:0,pickIndex:p});
const results=[];
function check(name, actual, expected) {assert.deepEqual(actual,expected,name);results.push({name,actual,expected,passed:true});}
check('empty selections',totalsFor([],10000),{odds:'0.000',potential:'0'});
check('single selection',totalsFor([pick(0)],10000),{odds:'1.840',potential:'18400'});
check('10000 * 1.84 * 1.56, final display rounding only',totalsFor([pick(0),pick(1)],10000),{odds:'2.870',potential:'28704'});
check('three decimal odds preserve precision and truncate won',totalsFor([pick(0),pick(1),pick(6,2)],10001),{odds:'6.100',potential:'61002'});
check('three decimal display',priceText(2.125),'2.125');
for (const raw of ['', 'abc', '-1000', '1000.5', '999', '100001', '9007199254740992']) check(`invalid stake ${JSON.stringify(raw)}`,!!validateStake(raw,1000000).error,true);
check('minimum',validateStake('1000',1000000),{value:1000,error:''});
check('maximum',validateStake('100000',1000000),{value:100000,error:''});
check('exact available balance',validateStake('1500',1500),{value:1500,error:''});
check('exceeds available balance',validateStake('1501',1500).error,'가상 잔액보다 큰 금액입니다.');
check('zero balance rejected',!!validateStake('1000',0).error,true);
const result={checkedAt:new Date().toISOString(),sourceSha256:require('node:crypto').createHash('sha256').update(source).digest('hex'),count:results.length,results};
fs.writeFileSync(path.join(__dirname,'calculation-check.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify({passed:results.length,report:'calculation-check.json'}));
